"""Backtest report as JSON and Markdown. These files are the only source for quoted error values."""

import csv
import json
from datetime import date, datetime
from pathlib import Path

from gridload.forecast.backtest import BacktestResult, Metric

LABELS = {
    "lightgbm": "LightGBM model",
    "baseline_week": "Baseline (same hour last week)",
    "tso": "SMARD grid load forecast",
}
DAY_TYPES = {
    "workday": "Workdays",
    "saturday": "Saturdays",
    "sunday_holiday": "Sundays and holidays",
}


def to_json(result: BacktestResult) -> str:
    data = {
        "first_day": result.first_day.isoformat(),
        "last_day": result.last_day.isoformat(),
        "config": result.config,
        "skipped_days": [d.isoformat() for d in result.skipped_days],
        "metrics": [
            {
                "model": m.model,
                "scope": m.scope,
                "scope_value": m.scope_value,
                "mae_mwh": round(m.mae, 1),
                "mape_percent": round(m.mape, 3),
                "n": m.n,
            }
            for m in result.metrics
        ],
    }
    return json.dumps(data, indent=2, sort_keys=True) + "\n"


def _find(metrics: list[Metric], model: str, scope: str, value: str) -> Metric:
    return next(m for m in metrics if (m.model, m.scope, m.scope_value) == (model, scope, value))


def to_markdown(result: BacktestResult) -> str:
    m = result.metrics
    models = [k for k in LABELS if any(x.model == k for x in m)]
    if not models:
        return "# Backtest\n\nNo hours with actual values and all predictions in the period.\n"
    n = _find(m, models[0], "overall", "all").n
    lines = [
        "# Backtest",
        "",
        f"Delivery days {result.first_day} to {result.last_day}, {n} hours scored. "
        "Generated by `scripts/backtest.py`; do not edit by hand.",
        "",
        "Each delivery day is forecast at 12:00 Europe/Berlin on the previous day, using only "
        "data up to 10:00. The model is retrained every "
        f"{result.config['retrain_every']} days on all earlier complete days (seed "
        f"{result.config['seed']}). All three forecasts are scored on the same hours.",
        "",
        "## Overall",
        "",
        "| Forecast | MAE (MWh per hour) | MAPE |",
        "|---|---:|---:|",
    ]
    for model in models:
        x = _find(m, model, "overall", "all")
        lines.append(f"| {LABELS[model]} | {x.mae:,.0f} | {x.mape:.2f} % |")
    lines += [
        "",
        "## By day type (MAPE)",
        "",
        "| Day type | " + " | ".join(LABELS[k] for k in models) + " |",
        "|---|" + "---:|" * len(models),
    ]
    for value, label in DAY_TYPES.items():
        cells = []
        for model in models:
            hit = [x for x in m if (x.model, x.scope, x.scope_value) == (model, "day_type", value)]
            cells.append(f"{hit[0].mape:.2f} % (n={hit[0].n})" if hit else "n/a")
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "## By local hour (MAPE)",
        "",
        "| Hour | " + " | ".join(LABELS[k] for k in models) + " |",
        "|---:|" + "---:|" * len(models),
    ]
    for hour in range(24):
        cells = []
        for model in models:
            hit = [x for x in m if (x.model, x.scope, x.scope_value) == (model, "hour", str(hour))]
            cells.append(f"{hit[0].mape:.2f} %" if hit else "n/a")
        lines.append(f"| {hour:02d}:00 | " + " | ".join(cells) + " |")
    lines += [
        "",
        "## Notes",
        "",
        "- The SMARD grid load forecast (filter 411) is scored with the values SMARD publishes "
        "today. SMARD does not state when each value was published or whether it was revised, "
        "so this comparison may favour that forecast.",
        "- MAE is in MWh per hour (equal to the mean absolute error in MW). MAPE is the mean "
        "absolute percentage error over all scored hours.",
    ]
    if result.skipped_days:
        lines.append(f"- Days without actual values, not scored: {len(result.skipped_days)}.")
    return "\n".join(lines) + "\n"


def write_rows(result: BacktestResult, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(
            [
                "delivery_day",
                "target_ts",
                "hour_local",
                "day_type",
                "actual",
                "lightgbm",
                "baseline_week",
                "tso",
            ]
        )
        for r in result.rows:
            writer.writerow(
                [
                    _cell(r[k])
                    for k in (
                        "delivery_day",
                        "target_ts",
                        "hour_local",
                        "day_type",
                        "actual",
                        "lightgbm",
                        "baseline_week",
                        "tso",
                    )
                ]
            )


def _cell(value: object) -> str:
    if isinstance(value, date | datetime):
        return value.isoformat()
    return str(value)
