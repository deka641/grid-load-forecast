"""Backtest report as JSON and Markdown. These files are the only source for quoted error values."""

import csv
import json
from datetime import date, datetime
from pathlib import Path

from gridload.forecast.backtest import BacktestResult, Metric, error_summary

LABELS = {
    "lightgbm": "LightGBM model",
    "baseline_week": "Baseline (same hour last week)",
    "tso": "SMARD grid load forecast",
}
DAY_TYPES = {
    "workday": "Workdays",
    "saturday": "Saturdays",
    "sunday_holiday": "Sundays and holidays",
}


def to_json(result: BacktestResult) -> str:
    data = {
        "first_day": result.first_day.isoformat(),
        "last_day": result.last_day.isoformat(),
        "config": result.config,
        "skipped_days": [d.isoformat() for d in result.skipped_days],
        "inputs": result.inputs,
        "error_distribution": {
            model: {
                "bias_mwh": round(x.bias, 1),
                "p95_abs_error_mwh": round(x.p95_abs, 1),
                "max_abs_error_mwh": round(x.max_abs, 1),
                "hours_above_5_percent": round(x.share_above_5_percent, 2),
                "n": x.n,
            }
            for model, x in error_summary(result.rows).items()
        },
        "metrics": [
            {
                "model": m.model,
                "scope": m.scope,
                "scope_value": m.scope_value,
                "mae_mwh": round(m.mae, 1),
                "mape_percent": round(m.mape, 3),
                "n": m.n,
            }
            for m in result.metrics
        ],
    }
    return json.dumps(data, indent=2, sort_keys=True) + "\n"


def _find(metrics: list[Metric], model: str, scope: str, value: str) -> Metric:
    return next(m for m in metrics if (m.model, m.scope, m.scope_value) == (model, scope, value))


def to_markdown(result: BacktestResult) -> str:
    m = result.metrics
    models = [k for k in LABELS if any(x.model == k for x in m)]
    if not models:
        return "# Backtest\n\nNo hours with actual values and all predictions in the period.\n"
    n = _find(m, models[0], "overall", "all").n
    lines = [
        "# Backtest",
        "",
        f"Delivery days {result.first_day} to {result.last_day}, {n} hours scored. "
        "Generated by `scripts/backtest.py`; do not edit by hand.",
        "",
        "Each delivery day is forecast at 12:00 Europe/Berlin on the previous day, using only "
        "hours that ended by 10:00. The model is retrained every "
        f"{result.config['retrain_every']} days on all earlier complete days (seed "
        f"{result.config['seed']}). The model and the baseline are scored on the same hours; "
        "the SMARD forecast on those of them where SMARD publishes a value.",
        "",
        "## Overall",
        "",
        "| Forecast | MAE (MWh per hour) | MAPE | Hours |",
        "|---|---:|---:|---:|",
    ]
    for model in models:
        x = _find(m, model, "overall", "all")
        lines.append(f"| {LABELS[model]} | {x.mae:,.0f} | {x.mape:.2f} % | {x.n} |")
    shared = [x for x in m if x.scope == "overall_tso_hours"]
    if shared:
        tso = _find(m, "tso", "overall", "all")
        parts = ", ".join(f"{LABELS[x.model]} {x.mape:.2f} %" for x in shared)
        lines += [
            "",
            f"On the {tso.n} hours that also have a SMARD forecast, the MAPE is: {parts}, "
            f"{LABELS['tso']} {tso.mape:.2f} %.",
        ]
    stats = error_summary(result.rows)
    if stats:
        lines += [
            "",
            "## Error distribution",
            "",
            "| Forecast | Bias (MWh per hour) | 95th percentile of absolute error (MWh) "
            "| Largest absolute error (MWh) | Hours with error above 5 % |",
            "|---|---:|---:|---:|---:|",
        ]
        for model, e in ((k, stats[k]) for k in models if k in stats):
            lines.append(
                f"| {LABELS[model]} | {e.bias:+,.0f} | {e.p95_abs:,.0f} | {e.max_abs:,.0f} "
                f"| {e.share_above_5_percent:.1f} % |"
            )
        lines += [
            "",
            "Bias is the mean of forecast minus actual; a positive value means the forecast "
            "is too high on average. The error above 5 % is the absolute percentage error of "
            "an hour. Each forecast is scored on the same hours as in the overall table.",
        ]
    lines += [
        "",
        "## By day type (MAPE)",
        "",
        "| Day type | " + " | ".join(LABELS[k] for k in models) + " |",
        "|---|" + "---:|" * len(models),
    ]
    for value, label in DAY_TYPES.items():
        cells = []
        for model in models:
            hit = [x for x in m if (x.model, x.scope, x.scope_value) == (model, "day_type", value)]
            cells.append(f"{hit[0].mape:.2f} % (n={hit[0].n})" if hit else "n/a")
        lines.append(f"| {label} | " + " | ".join(cells) + " |")
    lines += [
        "",
        "## By local hour (MAPE)",
        "",
        "| Hour | " + " | ".join(LABELS[k] for k in models) + " |",
        "|---:|" + "---:|" * len(models),
    ]
    for hour in range(24):
        cells = []
        for model in models:
            hit = [x for x in m if (x.model, x.scope, x.scope_value) == (model, "hour", str(hour))]
            cells.append(f"{hit[0].mape:.2f} %" if hit else "n/a")
        lines.append(f"| {hour:02d}:00 | " + " | ".join(cells) + " |")
    lines += [
        "",
        "## Notes",
        "",
        "- Two effects of the data point in opposite directions. The model's inputs are the "
        "load values as stored today, including corrections SMARD made later, which a forecast "
        "at 12:00 on the day before would not have had; this favours the model. The SMARD grid "
        "load forecast (filter 411) is scored with the values SMARD publishes today, without its "
        "publication time; this may favour SMARD. Neither effect is quantified, so the gap "
        "between the model and SMARD is an estimate, not a measured advantage.",
        "- MAE is in MWh per hour (equal to the mean absolute error in MW). MAPE is the mean "
        "absolute percentage error over all scored hours.",
        "- Hours are local time. The 02:00 row includes both 02:00 hours of the autumn "
        "clock-change day; the spring clock-change day has no 02:00 hour.",
    ]
    if result.inputs:
        lines.append(
            f"- Input data: SHA-256 `{result.inputs['sha256']}` over {result.inputs['hours']} "
            "hourly values of grid load and the SMARD forecast up to the last delivery day "
            f"(canonical form in `service.input_fingerprint`); {result.inputs['revised_hours']} "
            "of these hours contain a value that SMARD corrected after it was first loaded."
        )
    if result.skipped_days:
        lines.append(f"- Days without actual values, not scored: {len(result.skipped_days)}.")
    return "\n".join(lines) + "\n"


ROW_COLUMNS = (
    "delivery_day",
    "target_ts",
    "hour_local",
    "fold",
    "day_type",
    "actual",
    "lightgbm",
    "baseline_week",
    "tso",
)


def write_rows(result: BacktestResult, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(ROW_COLUMNS)
        for r in result.rows:
            writer.writerow([_cell(r[k]) for k in ROW_COLUMNS])


def _cell(value: object) -> str:
    if isinstance(value, date | datetime):
        return value.isoformat()
    return str(value)
